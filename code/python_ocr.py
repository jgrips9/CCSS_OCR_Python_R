from pdf2image import convert_from_path
from docx import Document
import pytesseract

def OCR_function(filename):

    pages = convert_from_path(
        filename,
        dpi=300
    )

    doc = Document()
    all_text = []

    for page_num, page in enumerate(pages, start=1):

        text = pytesseract.image_to_string(
            page,
            config="--oem 3 --psm 1"
        )

        all_text.append(text)

        doc.add_heading(
            f"Page {page_num}",
            level=1
        )

        doc.add_paragraph(text)

        print(f"Processed page {page_num}")

    base_name = filename.rsplit(".", 1)[0]

    txt_file = f"OCR_{base_name}.txt"
    docx_file = f"OCR_{base_name}.docx"

    with open(
        txt_file,
        "w",
        encoding="utf-8"
    ) as f:

        f.write("\n\n".join(all_text))

    doc.save(docx_file)

    files.download(txt_file)
    files.download(docx_file)

#Perform function on multiple files. txt and word document
filenames_list = ["W2_Interactive.pdf", "sample scanned letter.pdf"]
for j in filenames_list:
  OCR_function(j)